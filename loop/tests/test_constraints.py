def test_the_real_spec_is_accounted_and_clean(spec):
    """A canary on the checked-in spec, asserting what the loop guarantees
    rather than what one run happened to produce.

    The distill stage refuses to write this file with an `error` standing and
    promotes it with warnings standing, so `error` is the bar. The totals are
    checked against each other -- K.storage_bits re-derives from the formulas,
    resource_accounting states the sum -- which is the invariant that holds
    whatever the next run names its knobs.
    """
    errors = [f for f in spec_checks.run_checks(spec) if f.severity == "error"]
    assert errors == [], "\n".join(f"{f.pointer}: {f.message}" for f in errors)
    feature, host = K.default_values(K.all_knobs(spec, None))
    total, breakdown = K.storage_bits(spec, None, feature, host)
    assert total == spec["resource_accounting"]["total_storage_bits"]
    assert len(breakdown) == len(spec["state"])


def test_a_formula_that_disagrees_with_its_size_is_an_error(spec):
    """Double a formula the spec already wrote, so every name in it is one
    the spec declares. Writing knob names here pinned the test to whatever
    the last distill run happened to call them, and it then reported
    `formula_unknown_name` -- a different defect -- instead of failing."""
    entry = next((e for e in spec["state"] if e.get("size_formula")), None)
    if entry is None:
        pytest.skip("this spec states no size_formula")   # the field is optional
    entry["size_formula"] = f"2 * ({entry['size_formula']})"
    assert "formula_disagrees" in codes(spec_checks.run_checks(spec))


def test_a_formula_reading_an_undeclared_name_is_an_error(spec):
    spec["state"][1]["size_formula"] = "65 * 3 * ut_entries * counter_bits"
    assert "formula_unknown_name" in codes(spec_checks.run_checks(spec))


def test_a_storage_parameter_no_formula_reads_is_flagged(spec):
    """README's gap: nothing checked that the search could move the storage.

    Which parameters size a structure changes with every distill run, so the
    expectation is read off the formulas the spec states before they are
    stripped, not pinned to `/parameters/0` and `/parameters/4`.
    """
    sized = " ".join(str(s.get("size_formula", "")) for s in spec["state"])
    expected = {f"/parameters/{i}" for i, q in enumerate(spec["parameters"])
                if re.search(rf"\b{re.escape(q['name'])}\b", sized)}
    if not expected:
        pytest.skip("this spec states no size_formula naming a knob")
    for s in spec["state"]:
        s.pop("size_formula", None)
    found = [f for f in spec_checks.run_checks(spec)
             if f.code == "storage_param_unaccounted"]
    assert {f.pointer for f in found} >= expected
    assert all(f.severity == "warn" for f in found)


