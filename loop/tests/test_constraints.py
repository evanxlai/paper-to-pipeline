def test_shrinking_the_host_makes_room(spec, host):
    """How many banks the host must give back depends on how big the feature
    is, and that changes with every distill run -- the sR spec has ranged
    from 53863 to 92775 bits across the runs in out/. Solve for the shrink
    rather than pin it; what is under test is that one exists and that the
    accounting moves with it."""
    cs = [K.storage_constraint("iso-64KiB", 524288)]
    assert not K.check_static(
        dse.params_header(spec, host, constraint_set=cs), spec, host, cs).ok

    for nbh in range(20, -1, -1):
        header = dse.params_header(spec, host, host_overrides={"nbankhigh": nbh},
                                   constraint_set=cs)
        report = K.check_static(header, spec, host, cs)
        if report.ok:
            break
    else:
        pytest.fail("no legal nbankhigh: the host cannot pay for this feature")

    assert report.metrics["storage_bits"] <= 524288
    # Every bank given back is worth the same, so the total is the baseline
    # less a whole number of them.
    freed = feature_bits(spec) + HOST_BASELINE_BITS - report.metrics["storage_bits"]
    assert nbh == 20 or freed % (20 - nbh) == 0


def _refused(spec, host, edit):
    report = K.check_static(
        dse.params_header(spec, host).replace(*edit), spec, host, [])
    assert not report.ok
    return report.errors


