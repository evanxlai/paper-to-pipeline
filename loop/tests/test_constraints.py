def codes(findings):
    return sorted(f.code for f in findings)


# spec/sr.paper_only.json is regenerated by every distill run, and the
# distiller renames its knobs freely: `num_banks`, `NUM_BANKS`, `wt_num_banks`
# and `wt_banks` all name the same dimension across the runs in out/, and the
# count has ranged from four to fifteen. A test that pins a knob name or a
# storage total therefore goes red on the next run for a reason nobody should
# act on -- and a permanently red suite is how a real failure gets missed. So
# everything below derives what it needs from the spec in front of it.
#
# The host side is the opposite: fixtures/cbp2025.host_knobs.json is committed
# and hand-maintained, so its names and totals are safe to write down.
HOST_BASELINE_BITS = 524615


def feature_bits(spec):
    """What the spec's own formulas cost at their defaults."""
    feature, host = K.default_values(K.all_knobs(spec, None))
    total, _ = K.storage_bits(spec, None, feature, host)
    return total


def a_knob(spec, pred, why):
    """The first spec parameter matching `pred`.

    Skips rather than fails when this run's spec has no knob of the shape:
    the machinery is what is under test, and a spec that never grew one is
    not evidence the machinery broke.
    """
    for q in spec["parameters"]:
        if pred(q):
            return q, "SR_" + q["name"].upper()
    pytest.skip(f"the current spec declares no {why}")


def macro_cased(formula, spec):
    """A size_formula rewritten in the header's macro names."""
    for q in spec["parameters"]:
        formula = re.sub(rf"\b{re.escape(q['name'])}\b",
                         "SR_" + q["name"].upper(), formula)
    return formula


